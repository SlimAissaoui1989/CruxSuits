        public void Configure(EntityTypeBuilder<Locality> builder)
        {
            builder.HasIndex(locality => new { locality.AdministrativeAreaId, locality.Code })
                .IsUnique();

            builder.HasOne(locality => locality.AdministrativeArea)
                .WithMany()
                .HasForeignKey(locality => locality.AdministrativeAreaId)
                .OnDelete(DeleteBehavior.Restrict);

            builder.HasData(TunisianMunicipalities.Select(municipality =>
            {
                return new Locality
                {
                    Id = $"{municipality.AdministrativeAreaId}-{municipality.Code}",
                    AdministrativeAreaId = municipality.AdministrativeAreaId,
                    Code = municipality.Code,
                    CreatedDate = Shared.SharedValues.DefaultCreatedDate
                };
            }));
        }
